class TestLiveSimulationPipeline(unittest.TestCase):

    @classmethod
    def setUpClass(cls):
        cls.models_dir = predictor.models_dir
        cls.pipeline = DataCleaningPipeline(models_dir=cls.models_dir)
        cls.generator = ScenarioGenerator(seed=42)

    # -------------------------------------------------------------------------
    # 1. Sensor Data Generation & Determinism
    # -------------------------------------------------------------------------
    def test_01_sensor_data_generation_and_determinism(self):
        gen1 = ScenarioGenerator(seed=12345)
        gen2 = ScenarioGenerator(seed=12345)

        pkt1 = gen1.generate_cycle_reading("Engine-001", cycle=10, scenario=SimulationMode.HEALTHY, wear_index=0.1)
        pkt2 = gen2.generate_cycle_reading("Engine-001", cycle=10, scenario=SimulationMode.HEALTHY, wear_index=0.1)

        self.assertEqual(pkt1.sensors["s_4"], pkt2.sensors["s_4"])
        self.assertEqual(pkt1.sensors["s_11"], pkt2.sensors["s_11"])
        self.assertEqual(len(pkt1.sensors), 21, "Must contain all s_1 to s_21 C-MAPSS sensors")
        self.assertIn("setting_1", pkt1.operational_settings)
        self.assertIn("setting_2", pkt1.operational_settings)
        self.assertIn("setting_3", pkt1.operational_settings)

    # -------------------------------------------------------------------------
    # 2. Operating Scenario Progression (Healthy vs Gradual vs Critical)
    # -------------------------------------------------------------------------
    def test_02_scenario_progression(self):
        gen = ScenarioGenerator(seed=99)
        # Mode A: Healthy
        healthy_pkt = gen.generate_cycle_reading("ENG-A", cycle=20, scenario=SimulationMode.HEALTHY, wear_index=0.05)
        # Mode B: Gradual Degradation
        gradual_pkt = gen.generate_cycle_reading("ENG-B", cycle=120, scenario=SimulationMode.GRADUAL, wear_index=0.50)
        # Mode C: Critical Degradation
        critical_pkt = gen.generate_cycle_reading("ENG-C", cycle=220, scenario=SimulationMode.CRITICAL, wear_index=0.88)

        # In C-MAPSS, T50 exhaust temperature (s_4) and Ps30 static pressure (s_11) rise monotonically with degradation
        self.assertLess(healthy_pkt.sensors["s_4"], gradual_pkt.sensors["s_4"])
        self.assertLess(gradual_pkt.sensors["s_4"], critical_pkt.sensors["s_4"])
        self.assertLess(healthy_pkt.sensors["s_11"], critical_pkt.sensors["s_11"])

    # -------------------------------------------------------------------------
    # 3. Raw Data Validation & Schema Bounds Checking
    # -------------------------------------------------------------------------
    def test_03_data_validator_bounds_and_schema(self):
        validator = DataValidator()

        # Valid payload
        valid_packet = {
            "machine_id": "TEST-01",
            "sequence_number": 1,
            "sensors": {f"s_{i}": CMAPSS_SENSOR_SPECS[f"s_{i}"]["nominal_mean"] for i in range(1, 22)}
        }
        res_valid = validator.validate_packet(valid_packet)
        self.assertTrue(res_valid.is_valid)

        # Corrupted payload: Missing required sensor
        corrupt_packet = {
            "machine_id": "TEST-01",
            "sequence_number": 2,
            "sensors": {"s_2": 642.0, "s_3": "CORRUPTED_STRING", "s_4": None}
        }
        res_corrupt = validator.validate_packet(corrupt_packet)
        self.assertFalse(res_corrupt.is_valid)
        self.assertTrue(any("Missing required" in e or "Invalid non-numeric" in e for e in res_corrupt.errors))

    # -------------------------------------------------------------------------
    # 4. Outlier Detection & Clamping (IQR & Z-Score)
    # -------------------------------------------------------------------------
    def test_04_outlier_detection_and_clamping(self):
        detector = OutlierDetector(window_size=10, z_threshold=3.0)
        m_id = "OUTLIER_TEST"

        # Prime detector with nominal readings
        for _ in range(8):
            detector.process(m_id, {"s_4": 1406.0 + np.random.normal(0, 1.0)})

        # Inject extreme spike (+50 °R)
        spike_payload = {"s_4": 1465.0}
        outlier_res = detector.process(m_id, spike_payload)

        self.assertIn("s_4", outlier_res.outliers_found)
        self.assertLess(outlier_res.cleaned_sensors["s_4"], 1420.0, "Spike must be clamped towards rolling median")

    # -------------------------------------------------------------------------
    # 5. Missing Value Imputation (Forward Fill & Quarantine)
    # -------------------------------------------------------------------------
    def test_05_missing_value_handler(self):
        handler = MissingValueHandler(max_consecutive_missing=3)
        m_id = "MISS_TEST"

        # Establish last valid reading
        handler.process(m_id, {"s_4": 1408.5})

        # Single cycle dropout
        drop_res1 = handler.process(m_id, {"s_4": float("nan")})
        self.assertEqual(drop_res1.sensors["s_4"], 1408.5, "Single drop must forward-fill")
        self.assertFalse(drop_res1.quarantined)

        # Exceed allowable drop limit (>3)
        handler.process(m_id, {"s_4": float("nan")})
        handler.process(m_id, {"s_4": float("nan")})
        drop_res4 = handler.process(m_id, {"s_4": float("nan")})
        self.assertTrue(drop_res4.quarantined, "Excessive consecutive missing readings must trigger quarantine")

    # -------------------------------------------------------------------------
    # 6. Noise Reduction (Exponential Moving Average Filter)
    # -------------------------------------------------------------------------
    def test_06_noise_filter_ema(self):
        noise_filter = NoiseFilter(ema_alpha=0.30)
        m_id = "NOISE_TEST"

        # Initial baseline
        noise_filter.apply_filter(m_id, {"s_4": 1400.0})
        # Transient jitter
        filtered = noise_filter.apply_filter(m_id, {"s_4": 1410.0})

        # With alpha=0.3: 0.3*1410 + 0.7*1400 = 1403.0
        self.assertAlmostEqual(filtered["s_4"], 1403.0, delta=0.5)

    # -------------------------------------------------------------------------
    # 7. Feature Engineering (Drift, Rolling Means & Std)
    # -------------------------------------------------------------------------
    def test_07_feature_engineering_extraction(self):
        fe = FeatureEngineer(baseline_cycles=3)
        m_id = "FEAT_TEST"

        sensors_nom = {f"s_{i}": CMAPSS_SENSOR_SPECS[f"s_{i}"]["nominal_mean"] for i in range(1, 22)}
        settings = {"setting_1": 0.0, "setting_2": 0.0, "setting_3": 100.0}

        # Step 5 cycles
        feat = {}
        for c in range(1, 6):
            feat = fe.process(m_id, cycle=c, settings=settings, sensors=sensors_nom)

        self.assertIn("s_4_drift", feat)
        self.assertIn("s_4_rm5", feat)
        self.assertIn("s_4_rm15", feat)
        self.assertIn("s_4_rstd10", feat)

    # -------------------------------------------------------------------------
    # 8. Model Input Dimension & Schema Verification (FD001, FD002, FD003)
    # -------------------------------------------------------------------------
    def test_08_model_transformer_schema_verification(self):
        transformer = ModelTransformer(models_dir=self.models_dir)

        # FD001 Tabular DataFrame
        dummy_eng = {c: 1.0 for c in transformer.feature_schemas["FD001"]}
        df_fd001 = transformer.transform_fd001_tabular(dummy_eng)
        self.assertEqual(df_fd001.shape, (1, 78), "FD001 input must match 78 features exactly")

        # FD002 Sliding Window Tensor (30 cycles, 17 normalized features)
        m_id = "FD002_TEST"
        sensors = {f"s_{i}": CMAPSS_SENSOR_SPECS[f"s_{i}"]["nominal_mean"] for i in range(1, 22)}
        settings = {"setting_1": 0.0, "setting_2": 0.0, "setting_3": 100.0}

        for c in range(1, 15):
            transformer.append_sequence_observation(m_id, cycle=c, settings=settings, sensors=sensors)

        tensor_seq, tab_last = transformer.transform_multiregime_window(m_id, subset="FD002", window_size=30)
        self.assertIsNotNone(tensor_seq)
        self.assertEqual(tensor_seq.shape, (1, 30, 17), "FD002 tensor input must match (batch=1, seq_len=30, channels=17)")

    # -------------------------------------------------------------------------
    # 9. ML Model Inference on Actual Trained Artifacts
    # -------------------------------------------------------------------------
    def test_09_actual_trained_models_inference(self):
        # 9A: FD001 XGBoost Regressor
        res_fd001 = predictor.predict_cmaps_cleaned(
            machine_id="TEST-FD001",
            subset="FD001",
            cycle=50,
            operational_settings={"setting_1": 0.0, "setting_2": 0.0, "setting_3": 100.0},
            cleaned_sensors={"s_2": 642.7, "s_3": 1589.0, "s_4": 1406.0}
        )
        self.assertTrue(res_fd001["success"])
        self.assertFalse(res_fd001["isMock"])
        self.assertIn("xgb_regressor_FD001", res_fd001["modelVersion"])
        self.assertGreater(res_fd001["prediction"]["predictedRUL"], 0)

        # 9B: FD002 Attention-CNN-BiLSTM PyTorch Model
        trans = ModelTransformer(models_dir=self.models_dir)
        sensors = {f"s_{i}": CMAPSS_SENSOR_SPECS[f"s_{i}"]["nominal_mean"] for i in range(1, 22)}
        # Elevate exhaust temp to simulate degradation
        sensors["s_4"] = 1435.0
        sensors["s_11"] = 48.5
        for c in range(1, 32):
            trans.append_sequence_observation("TEST-FD002", cycle=c, settings={"setting_1": 0.0, "setting_2": 0.0, "setting_3": 100.0}, sensors=sensors)

        res_fd002 = predictor.predict_cmaps_cleaned(
            machine_id="TEST-FD002",
            subset="FD002",
            cycle=32,
            operational_settings={"setting_1": 0.0, "setting_2": 0.0, "setting_3": 100.0},
            cleaned_sensors=sensors,
            transformer=trans
        )
        self.assertTrue(res_fd002["success"])
        self.assertIn("Attention-CNN-BiLSTM", res_fd002["architecture"])
        self.assertLessEqual(res_fd002["prediction"]["predictedRUL"], 45, "Severe wear must predict low RUL")
        self.assertIn(res_fd002["prediction"]["riskLevel"], ["high", "critical"])

    # -------------------------------------------------------------------------
    # 10. Sensor Adapters (Industrial Workshop to C-MAPSS)
    # -------------------------------------------------------------------------
    def test_10_industrial_sensor_adapter(self):
        adapter = IndustrialWorkshopAdapter()
        raw_workshop = {
            "vibration": 5.2, # high vibration
            "toolWear": 210.0, # high wear
            "processTemperature": 322.0,
            "airTemperature": 298.0,
            "torque": 55.0,
            "rotationalSpeed": 1400.0
        }
        settings, sensors, warnings = adapter.adapt(raw_workshop)

        self.assertIn("s_4", sensors)
        self.assertIn("s_11", sensors)
        self.assertGreater(sensors["s_4"], 1406.8, "Tool wear must elevate exhaust temp proxy")
        self.assertTrue(any("PHYSICAL_ADAPTER_ACTIVE" in w for w in warnings))

    # -------------------------------------------------------------------------
    # 11. End-to-End Pipeline Execution & Metrics
    # -------------------------------------------------------------------------
    def test_11_end_to_end_pipeline_flow(self):
        pipe = DataCleaningPipeline(models_dir=self.models_dir)
        gen = ScenarioGenerator(seed=777)

        # Feed 10 packets
        for c in range(1, 11):
            pkt = gen.generate_cycle_reading("E2E-ENGINE", cycle=c, scenario=SimulationMode.GRADUAL, wear_index=c * 0.05)
            frame = pipe.process(pkt)
            self.assertEqual(frame.machine_id, "E2E-ENGINE")
            self.assertEqual(len(frame.comparison_table), 21)

        metrics = pipe.get_metrics()
        self.assertEqual(metrics.total_raw_readings, 10)
        self.assertGreater(metrics.cleaning_success_rate, 90.0)

    # -------------------------------------------------------------------------
    # 12. Simulation Manager Start/Pause/Resume/Stop Controls
    # -------------------------------------------------------------------------
    def test_12_simulation_manager_lifecycle(self):
        sim = SimulationManager(models_dir=self.models_dir)
        cfg = SimulationManagerConfig(tick_interval_seconds=0.5, speed_multiplier=2.0)

        # Start
        st_start = sim.configure_and_start(cfg)
        self.assertTrue(st_start.is_running)
        self.assertFalse(st_start.is_paused)

        # Pause
        st_pause = sim.pause()
        self.assertTrue(st_pause.is_paused)

        # Resume
        st_res = sim.resume()
        self.assertFalse(st_res.is_paused)

        # Stop
        st_stop = sim.stop()
        self.assertFalse(st_stop.is_running)

    # -------------------------------------------------------------------------
    # 13. SSE Queue Subscription and Real-Time Event Dispatch
    # -------------------------------------------------------------------------
    def test_13_sse_queue_event_dispatch(self):
        sim = SimulationManager(models_dir=self.models_dir)
        sub_queue = sim.subscribe_sse()

        try:
            # Step machine and process packet
            pkt = sim.simulator.step_machine("Engine-001")
            sim._process_single_packet(pkt)

            # Queue must receive payload
            received_item = sub_queue.get(timeout=2.0)
            self.assertEqual(received_item["type"], "telemetry_tick")
            self.assertEqual(received_item["machine_id"], "Engine-001")
            self.assertIn("prediction", received_item)
            self.assertIn("comparison_table", received_item)
        finally:
            sim.unsubscribe_sse(sub_queue)


